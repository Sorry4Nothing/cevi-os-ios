import Foundation

/// What kind of file a download is. The app checks the first bytes before it keeps a file (never the name the server gives).
nonisolated enum CampDownloadKind: String, Codable, Sendable {
    case calendar, pdf

    var fileExtension: String { self == .calendar ? "ics" : "pdf" }
    static let maxBytes = 20_000_000

    func accepts(_ data: Data) -> Bool {
        guard !data.isEmpty, data.count <= Self.maxBytes else { return false }
        let head = String(decoding: data.prefix(32), as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines.union(.init(charactersIn: "\u{FEFF}")))
        return self == .pdf ? head.hasPrefix("%PDF-") : head.uppercased().hasPrefix("BEGIN:VCALENDAR")
    }
}

/// A file the person can download on purpose.
nonisolated enum CampDownloadSource: Hashable, Sendable {
    case meetingCalendar(UUID)
    case handout(CampHandout)

    var key: String {
        switch self {
        case .meetingCalendar(let id): "hoeck-kalender:" + id.uuidString.lowercased()
        case .handout(let handout): "aushang:" + handout.rawValue
        }
    }

    var kind: CampDownloadKind {
        switch self {
        case .meetingCalendar: .calendar
        case .handout: .pdf
        }
    }
}

/// An entry of the list «Heruntergeladene Dateien». `fileName` is generated by the app (UUID and extension).
nonisolated struct CampDownload: Codable, Equatable, Identifiable, Sendable {
    let id: UUID
    let campId: UUID
    let campTitle: String
    let title: String
    let sourceKey: String
    let kind: CampDownloadKind
    let fileName: String
    let savedAt: Date
    let size: Int
}

nonisolated enum CampDownloadError: Error, Equatable, Sendable {
    /// Not a file of the expected kind, empty or too big.
    case invalid
    case storage
}
